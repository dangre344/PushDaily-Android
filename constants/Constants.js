export const DAY_LABELS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

// ─── Get local date string "YYYY-MM-DD" without timezone shift ───────────────
const toLocalDateKey = (date) => {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
};

// Returns Sunday of the current week using LOCAL date
const getSunday = () => {
  const today = new Date();
  const day = today.getDay(); // 0 = Sun, 1 = Mon ...
  const sunday = new Date(today);
  sunday.setDate(today.getDate() - day);
  sunday.setHours(0, 0, 0, 0);
  return sunday;
};

// Returns 7 LOCAL date strings "YYYY-MM-DD" starting from Sunday
const getCurrentWeekDates = () => {
  const sunday = getSunday();
  return Array.from({ length: 7 }, (_, i) => {
    const d = new Date(sunday);
    d.setDate(sunday.getDate() + i);
    return toLocalDateKey(d); // ← local, not UTC
  });
};

export const useWeeklyWorkouts = (workouts) => {
  const weekDates = getCurrentWeekDates();

  const todayKey = toLocalDateKey(new Date());

  const workoutMap = {};

  workouts.forEach((w) => {
    const localKey = toLocalDateKey(new Date(w.dateTime));
    if (!workoutMap[localKey]) {
      workoutMap[localKey] = w.bodyPart;
    }
  });

  const weeklyWorkouts = weekDates.map((dateKey, index) => {
    const isFuture = dateKey > todayKey;

    return {
      day: index,
      dateKey,
      isWorkout: isFuture ? null : !!workoutMap[dateKey], // 👈 key change
      bodyPart: workoutMap[dateKey] || null,
    };
  });

  const attendedDays = weeklyWorkouts.filter(
    (d) => d.isWorkout === true,
  ).length;

  return { weeklyWorkouts, attendedDays };
};

