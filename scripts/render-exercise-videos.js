#!/usr/bin/env node
// Renders exercise animations to looping MP4s that the app plays with the
// phone's hardware video decoder. Drawing the SVGs live (react-native-svg)
// costs ~450 ms per frame on mid-range phones; a video costs almost nothing.
//
// Each library SVG is drawn frame by frame in Chrome (it plays the SMIL
// natively) at 480 × 480, 24 fps, for exactly one loop so the clip repeats
// seamlessly, then encoded as H.264 Main profile (decodable on every Android
// phone). Output:
//   assets/exercise-videos/<slug>.mp4
//   assets/exercise-videos/index.js   — { slug: require("./slug.mp4") }, generated
// Then run scripts/map-exercise-videos.js to set `video: "<slug>"` on each
// exercise in constants/Constants.js.
//
// Usage:
//   node scripts/render-exercise-videos.js --body-part Chest
//   node scripts/render-exercise-videos.js push_ups wall_push_ups
//   node scripts/render-exercise-videos.js --all        (skips existing; --force redoes them)
// Needs Chrome plus two tools not kept in package.json (they're large and only
// needed here):  npm i --no-save puppeteer-core ffmpeg-static
// Library: EXERCISE_SVG_DIR (default C:/Users/gagan/workoutsvg/dist/svgs).
// Chrome:  CHROME_PATH (default C:/Program Files/Google/Chrome/Application/chrome.exe).

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

let puppeteer, ffmpeg;
try {
  puppeteer = require("puppeteer-core");
  ffmpeg = require("ffmpeg-static");
} catch {
  console.error("Missing tools. Run:  npm i --no-save puppeteer-core ffmpeg-static");
  process.exit(1);
}

const LIB = process.env.EXERCISE_SVG_DIR || "C:/Users/gagan/workoutsvg/dist/svgs";
const CHROME = process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe";
const OUT = path.join(__dirname, "..", "assets", "exercise-videos");
const CONSTANTS = path.join(__dirname, "..", "constants", "Constants.js");
const SIZE = 480;
const FPS = 24;
const CRF = 26; // visually identical to the SVG for this flat art (see samples)

/** Loop length: the longest animation in the SVG (all loop from t = 0). */
const loopSeconds = (svg) =>
  Math.max(...[...svg.matchAll(/\bdur="([\d.]+)s"/g)].map((m) => parseFloat(m[1])), 1);

/** Slugs used by one body part's workouts in workoutListGlobal. */
function slugsForBodyPart(part) {
  const slugs = new Set();
  let current = null;
  for (const line of fs.readFileSync(CONSTANTS, "utf8").split(/\r?\n/)) {
    const bp = line.match(/^ {4}bodyPart: "([^"]+)"/);
    if (bp) current = bp[1];
    const sv = line.match(/^ {8}svg: "([^"]+)"/);
    if (sv && current === part) slugs.add(sv[1]);
  }
  return [...slugs].sort();
}

function writeIndex() {
  const slugs = fs
    .readdirSync(OUT)
    .filter((f) => f.endsWith(".mp4"))
    .map((f) => f.slice(0, -4))
    .sort();
  fs.writeFileSync(
    path.join(OUT, "index.js"),
    "// GENERATED by scripts/render-exercise-videos.js — do not edit.\n" +
      "// Looping exercise videos, keyed by the `video` slug in constants/Constants.js.\n" +
      "module.exports = {\n" +
      slugs.map((s) => `  ${s}: require("./${s}.mp4"),`).join("\n") +
      "\n};\n",
  );
  return slugs.length;
}

(async () => {
  const args = process.argv.slice(2);
  const bpIndex = args.indexOf("--body-part");
  const slugs = args.includes("--all")
    ? fs.readdirSync(LIB).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4))
    : bpIndex >= 0
      ? slugsForBodyPart(args[bpIndex + 1])
      : args.filter((a) => !a.startsWith("--"));
  if (!slugs.length) {
    console.log("usage: node scripts/render-exercise-videos.js --body-part Chest | <slug…> | --all");
    process.exit(1);
  }

  fs.mkdirSync(OUT, { recursive: true });
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
  const page = await browser.newPage();
  await page.setViewport({ width: SIZE, height: SIZE });
  let total = 0;

  const force = args.includes("--force");
  for (const slug of slugs) {
    const out = path.join(OUT, `${slug}.mp4`);
    if (!force && fs.existsSync(out)) {
      total += fs.statSync(out).size / 1024;
      continue; // already rendered (re-render with --force)
    }
    const svg = fs.readFileSync(path.join(LIB, `${slug}.svg`), "utf8");
    const frames = Math.round(loopSeconds(svg) * FPS); // frame N == frame 0 → seamless loop
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), `exvid-${slug}-`));
    await page.setContent(
      `<html><body style="margin:0">${svg.replace(/width="100%" height="100%"/, `width="${SIZE}" height="${SIZE}"`)}</body></html>`,
    );
    for (let f = 0; f < frames; f++) {
      await page.evaluate((t) => {
        const s = document.querySelector("svg");
        s.pauseAnimations();
        s.setCurrentTime(t);
      }, f / FPS);
      await page.screenshot({ path: path.join(tmp, `f${String(f).padStart(4, "0")}.png`) });
    }
    execFileSync(ffmpeg, [
      "-y", "-loglevel", "error", "-framerate", String(FPS), "-i", path.join(tmp, "f%04d.png"),
      "-c:v", "libx264", "-preset", "veryslow", "-tune", "animation", "-crf", String(CRF),
      "-profile:v", "main", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", out,
    ]);
    fs.rmSync(tmp, { recursive: true, force: true });
    const kb = fs.statSync(out).size / 1024;
    total += kb;
    console.log(`${slug.padEnd(32)} ${(frames / FPS).toFixed(1)}s  ${kb.toFixed(0)} KB`);
  }
  await browser.close();

  const count = writeIndex();
  console.log(`\nrendered ${slugs.length} (${(total / 1024).toFixed(2)} MB) · index lists ${count} videos`);
})();
