#!/usr/bin/env node
// Embeds Jack's widget PNGs into the Cloudflare Worker so it can serve them at
//   https://<worker>/jack/<mood>.png
// for the picture in push notifications. Re-run after changing the art:
//   node scripts/build-worker-jack-images.js
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "assets", "widget");
const OUT = path.join(__dirname, "..", "server", "trainer-worker", "jackImages.js");

const entries = fs
  .readdirSync(SRC)
  .filter((f) => /^mascot_[a-z]+\.png$/.test(f))
  .sort()
  .map((f) => {
    const mood = f.replace(/^mascot_|\.png$/g, "");
    return `  ${mood}: "${fs.readFileSync(path.join(SRC, f)).toString("base64")}",`;
  });

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/build-worker-jack-images.js — do not edit by hand.
// Jack's moods as base64 PNGs (256×256), served at /jack/<mood>.png.
export const JACK_PNG = {
${entries.join("\n")}
};
`,
);
console.log(`wrote ${entries.length} images → ${path.relative(process.cwd(), OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
